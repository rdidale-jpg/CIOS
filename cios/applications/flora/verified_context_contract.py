"""Read-only interface required of a future verified 01B producer.

These Protocols describe projections, not credentials. Implementing their shape,
constructing a matching object, or passing one as request data conveys no trust.
01A installs no producer, issuer, registry, session or membership persistence.
"""
from __future__ import annotations
from datetime import datetime
from typing import Protocol


class VerifiedMembership(Protocol):
    @property
    def membership_id(self) -> str: ...
    @property
    def user_id(self) -> str: ...
    @property
    def workspace_id(self) -> str: ...
    @property
    def roles(self) -> frozenset[str]: ...
    @property
    def version(self) -> int: ...
    @property
    def active(self) -> bool: ...
    @property
    def checked_at(self) -> datetime: ...


class VerifiedSession(Protocol):
    @property
    def session_ref(self) -> str: ...
    @property
    def authenticated_at(self) -> datetime: ...
    @property
    def expires_at(self) -> datetime: ...
    @property
    def idle_expires_at(self) -> datetime: ...
    @property
    def reauthenticated_at(self) -> datetime | None: ...
    @property
    def revoked(self) -> bool: ...
    @property
    def revocation_version(self) -> int: ...
    @property
    def checked_at(self) -> datetime: ...


class VerifiedContext(Protocol):
    @property
    def user_id(self) -> str: ...
    @property
    def verified_human(self) -> bool: ...
    @property
    def authentication_source(self) -> str: ...
    @property
    def workspace(self) -> str: ...
    @property
    def workspace_ids(self) -> frozenset[str]: ...
    @property
    def membership(self) -> VerifiedMembership | None: ...
    @property
    def roles(self) -> frozenset[str]: ...
    @property
    def effective_capabilities(self) -> frozenset[str]: ...
    @property
    def enterprise_ids(self) -> frozenset[str]: ...
    @property
    def session(self) -> VerifiedSession: ...
